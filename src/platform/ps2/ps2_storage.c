/*
 * PS2 storage bootstrap - see ps2_storage.h for the design notes.
 *
 * Module bring-up is tiered so the risky stacks are only touched when the
 * cheap ones did not produce a "mass:" device:
 *
 *   tier 1  usbd + usbhdfsd                          USB stick (classic)
 *   tier 2  bdm + usbmass_bd + bdmfs_fatfs           BDM USB (OPL-style)
 *   tier 3  sio2man + mx4sio_bd + (bdm stack)        MX4SIO
 *
 * Every load result is logged; failures (including "already loaded") never
 * stop the boot because the game may well be reading from mc0/host/cdrom
 * instead.
 */

#include "ps2_storage.h"

#include <dirent.h>
#include <stdio.h>
#include <string.h>

#include <loadfile.h>
#include <sifrpc.h>

#define PS2_STORAGE_DIR_MAX 64

static char s_elf_dir[PS2_STORAGE_DIR_MAX];
static int s_elf_dir_ok;

/* Generated by CMake from $PS2SDK/iop/irx (binary blobs as C arrays). */
extern const unsigned char g_ps2_usbd_irx[];
extern const unsigned int g_ps2_usbd_irx_size;
extern const unsigned char g_ps2_usbhdfsd_irx[];
extern const unsigned int g_ps2_usbhdfsd_irx_size;
extern const unsigned char g_ps2_bdm_irx[];
extern const unsigned int g_ps2_bdm_irx_size;
extern const unsigned char g_ps2_usbmass_bd_irx[];
extern const unsigned int g_ps2_usbmass_bd_irx_size;
extern const unsigned char g_ps2_bdmfs_fatfs_irx[];
extern const unsigned int g_ps2_bdmfs_fatfs_irx_size;
extern const unsigned char g_ps2_sio2man_irx[];
extern const unsigned int g_ps2_sio2man_irx_size;
extern const unsigned char g_ps2_mx4sio_bd_irx[];
extern const unsigned int g_ps2_mx4sio_bd_irx_size;

/* ------------------------------------------------------- argv0 parsing --- */

static const char* storage_last_sep(const char* s)
{
    const char* best = NULL;

    while (*s != '\0') {
        if (*s == '/' || *s == '\\') {
            best = s;
        }
        s++;
    }

    return best;
}

static void storage_extract_elf_dir(const char* argv0)
{
    const char* sep;
    const char* colon;
    const char* p;
    size_t len;
    int i;

    s_elf_dir_ok = 0;

    if (argv0 == NULL || argv0[0] == '\0') {
        return;
    }

    /* Some loaders hand the path over quoted. */
    if (argv0[0] == '"') {
        argv0++;
    }

    sep = storage_last_sep(argv0);
    colon = strchr(argv0, ':');

    if (sep != NULL) {
        if (colon == NULL) {
            /* Deviceless relative path: nothing we can probe directly. */
            return;
        }
        len = (size_t)(sep - argv0) + 1; /* keep the trailing separator */
    } else if (colon != NULL) {
        len = (size_t)(colon - argv0) + 1; /* device root, e.g. "mass:" */
    } else {
        /* Bare file name: not usable for probing. */
        return;
    }

    if (len == 0 || len + 2 > sizeof(s_elf_dir)) {
        return;
    }

    memcpy(s_elf_dir, argv0, len);
    for (i = 0; i < (int)len; i++) {
        if (s_elf_dir[i] == '\\') {
            s_elf_dir[i] = '/';
        }
    }
    if (s_elf_dir[len - 1] != '/') {
        s_elf_dir[len++] = '/';
    }
    s_elf_dir[len] = '\0';
    s_elf_dir_ok = 1;
}

const char* ps2_storage_elf_dir(void)
{
    return s_elf_dir_ok ? s_elf_dir : NULL;
}

/* --------------------------------------------------------- IOP modules --- */

static int storage_device_present(const char* dir)
{
    char tmp[PS2_STORAGE_DIR_MAX + 2];
    DIR* d;

    d = opendir(dir);
    if (d != NULL) {
        closedir(d);
        return 1;
    }

    if (snprintf(tmp, sizeof(tmp), "%s/", dir) < (int)sizeof(tmp)) {
        d = opendir(tmp);
        if (d != NULL) {
            closedir(d);
            return 1;
        }
    }

    return 0;
}

static int storage_mass_present(void)
{
    return storage_device_present("mass:") || storage_device_present("mass0:");
}

static int storage_exec_irx(const char* name, const unsigned char* data, unsigned int size)
{
    int result = 0;
    int ret = SifExecModuleBuffer((void*)data, size, 0, NULL, &result);

    if (ret >= 0) {
        printf("[ps2] storage: %s loaded (id %d, result %d)\n", name, ret, result);
        return 0;
    }

    /* The usual failure is "already loaded" (OPL/uLaunchELF preload their
     * IOP stack); a missing dependency or dead device lands here too. Both
     * are non-fatal: the device probe below is the real test. */
    printf("[ps2] storage: %s not loaded (ret %d, result %d) - continuing\n", name, ret, result);
    return -1;
}

void ps2_storage_init(const char* argv0)
{
    printf("[ps2] storage: ELF argv0 = '%s'\n", argv0 != NULL ? argv0 : "");

    storage_extract_elf_dir(argv0);
    if (s_elf_dir_ok) {
        printf("[ps2] storage: ELF directory = '%s'\n", s_elf_dir);
    }

    /* Loader-managed I/O: OPL mounts USB/MX4SIO/HDD itself, uLaunchELF the
     * same, ps2link provides host:, PCSX2 emulates host:. Leave the IOP
     * untouched in all of those cases. */
    if (storage_mass_present()) {
        printf("[ps2] storage: mass: already available (loader-managed)\n");
        return;
    }
    if (storage_device_present("host:")) {
        printf("[ps2] storage: host: available (development I/O), skipping USB bring-up\n");
        return;
    }

    printf("[ps2] storage: bringing up USB mass storage\n");
    sceSifInitRpc(0);

    storage_exec_irx("usbd.irx", g_ps2_usbd_irx, g_ps2_usbd_irx_size);
    storage_exec_irx("usbhdfsd.irx", g_ps2_usbhdfsd_irx, g_ps2_usbhdfsd_irx_size);

    if (!storage_mass_present()) {
        /* BDM block-device layer (also the base for MX4SIO below). */
        storage_exec_irx("bdm.irx", g_ps2_bdm_irx, g_ps2_bdm_irx_size);
        storage_exec_irx("usbmass_bd.irx", g_ps2_usbmass_bd_irx, g_ps2_usbmass_bd_irx_size);
        storage_exec_irx("bdmfs_fatfs.irx", g_ps2_bdmfs_fatfs_irx, g_ps2_bdmfs_fatfs_irx_size);
    }

    if (!storage_mass_present()) {
        /* MX4SIO: SIO2-based memory card port adapter. */
        storage_exec_irx("sio2man.irx", g_ps2_sio2man_irx, g_ps2_sio2man_irx_size);
        storage_exec_irx("mx4sio_bd.irx", g_ps2_mx4sio_bd_irx, g_ps2_mx4sio_bd_irx_size);
    }

    if (storage_mass_present()) {
        printf("[ps2] storage: mass: ready\n");
    } else {
        printf("[ps2] storage: mass: not available\n");
    }
}
